function blank() {
  const g = [];
  for (let y = 0; y < H; y++) {
    const row = [];
    for (let x = 0; x < W; x++) row.push((y === 0 || y === H - 1 || x === 0 || x === W - 1) ? '#' : ' ');
    g.push(row);
  }
  return g;
}
const slab = (g, x0, x1, y) => { for (let x = x0; x <= x1; x++) g[y][x] = '#'; };
