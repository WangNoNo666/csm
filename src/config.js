// 方向向量工具
const DIR = {
  0: { x: 0, y: -1 },   // 上（地面朝上）
  1: { x: 1, y: 0 },    // 右
  2: { x: 0, y: 1 },    // 下（天花板）
  3: { x: -1, y: 0 },   // 左
};
function dirOf(x, y) {
  if (y === -1) return 0;
  if (x === 1) return 1;
  if (y === 1) return 2;
  return 3;
}
